"""Write src/shared/Config/CeremonyConfig.luau: everything the podium ceremony needs (GAME_DESIGN §40.5 "The podium
ceremony", user 2026-11-25), from the files that made it, so no number is typed by hand.

    python art/scripts/make_ceremony_config.py

Reads art/exports/WornMedal_01_fit.json (the worn medal's per-build offsets on the UpperTorso, the held medals' hold
points: art/scripts/build_worn_medal_01.py, build_held_medal_open_01.py) and art/exports/WornMedal_01_upload.json
(the medal pieces' uploaded model ids). The animation ids are the uploads of 2026-11-25 (art/scripts/upload_animations.py
on the clips art/scripts/ceremony_animations.py wrote); the times and placements are that script's (its notes and
PLACEMENT table).
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FIT = json.loads((ROOT / "art" / "exports" / "WornMedal_01_fit.json").read_text(encoding="utf-8"))
UPLOAD = json.loads((ROOT / "art" / "exports" / "WornMedal_01_upload.json").read_text(encoding="utf-8"))
OUT = ROOT / "src" / "shared" / "Config" / "CeremonyConfig.luau"
BUILDS = ["Skinny", "SkinnyFat", "Fit", "Fat", "Muscular", "BigBuff"]

ANIMATIONS = {  # uploaded 2026-11-25 with the user's OK ("Upload")
    "LifterHandshake": "rbxassetid://120453127417264",
    "LifterReceiveMedal": "rbxassetid://129074568143660",
    "LifterStepUp": "rbxassetid://123969946044186",
    "RefHandTrophy": "rbxassetid://113216522317063",
    "RefHandshake": "rbxassetid://140053972372370",
    "RefPlaceMedal": "rbxassetid://86785197661365",
}
TAKE_TROPHY = {  # one per build: the two hands of the six builds sit up to ~1 stud apart differently
    "Skinny": "rbxassetid://91278767255556", "SkinnyFat": "rbxassetid://118649516842263",
    "Fit": "rbxassetid://73823108897103", "Fat": "rbxassetid://127780101705527",
    "Muscular": "rbxassetid://94629322553313", "BigBuff": "rbxassetid://115913484881419",
}
# refRoot = lifterRoot * CFrame.new(x, 0, -d) * CFrame.Angles(0, math.pi, 0)  (ceremony_animations.py PLACEMENT)
MEDAL_D = {"Skinny": 3.183, "SkinnyFat": 3.183, "Fit": 3.257, "Fat": 3.322, "Muscular": 3.339, "BigBuff": 3.455}
HANDSHAKE = {"Skinny": (0.166, 3.346), "SkinnyFat": (0.237, 3.388), "Fit": (0.353, 3.466), "Fat": (0.467, 3.523),
             "Muscular": (0.516, 3.613), "BigBuff": (0.626, 3.681)}
TROPHY_D = 4.100
# The trophy's pivot (base bottom centre) from the lifter's RightWristRigAttachment once taken, all builds turned
# fromEulerAnglesXYZ(-1.8158, 0, 0); and from the referee's at the start.
TROPHY_LIFTER_POS = {"Skinny": (-0.572, -0.006, 0.964), "SkinnyFat": (-0.584, -0.024, 0.958), "Fit": (-0.602, -0.049, 0.950),
                     "Fat": (-0.616, -0.070, 0.944), "Muscular": (-0.652, -0.121, 0.928), "BigBuff": (-0.666, -0.141, 0.921)}


def lua_cf(v):
    return "CFrame.new(" + ", ".join(f"{x:g}" for x in v) + ")"


def lua_v3(v):
    return "Vector3.new(" + ", ".join(f"{x:g}" for x in v) + ")"


def main():
    ids = {name: e.get("ids", {}).get("model", "") for name, e in UPLOAD["models"].items()}
    missing = [n for n, i in ids.items() if not i]
    if missing:
        raise SystemExit(f"not uploaded yet: {missing}")
    o = ['--!strict', '--[[', '\tCeremonyConfig', '\tShared / Config', '',
         '\tGENERATED by art/scripts/make_ceremony_config.py: do not edit by hand.',
         '\tTHE PODIUM CEREMONY (GAME_DESIGN §40.5 "The podium ceremony", user 2026-11-25): the top 3 are called one by one',
         '\t(3rd, 2nd, 1st); in front of their block a referee puts a medal over the neck (Local, Regional; 2nd and 3rd at',
         '\tState and Nationals) or hands 1st the trophy (State, Nationals), they shake hands, then the lifter hops up.',
         '\tThe medal\'s pieces, its offsets per body build (UpperTorso part space), the clips, their times (seconds into',
         '\teach clip) and where the referee stands (refRoot = lifterRoot * CFrame.new(x, 0, -d) * Angles(0, pi, 0)).',
         ']]', '', 'local CeremonyConfig = {}', '']
    o.append('-- The medal pieces (Model assets with one MeshPart each, named as the key).')
    o.append('CeremonyConfig.MedalAssets = {')
    for n, i in ids.items():
        o.append(f'\t{n} = {str(i).replace("rbxassetid://", "")},')  # (numbers: InsertService:LoadAsset takes ids)
    o.append('}')
    o.append('')
    o.append('-- Gold, silver, bronze: StarterGymConfig.PropPaints names (bronze text in Cream: Coffee on bronze did not read).')
    ways = [dict(w) for w in FIT["colourways"]]
    ways[2]["Text"] = "Cream"
    o.append('CeremonyConfig.MedalPaints = {')
    for w in ways:
        o.append('\t{ ' + ", ".join(f'{k} = "{v}"' for k, v in w.items()) + ' },')
    o.append('}')
    o.append('')
    o.append('-- The worn medal on each build: each piece welded to the UpperTorso at this C0 (Disc and Text shared meshes,')
    o.append('-- the ribbon its own per build).')
    o.append('CeremonyConfig.Worn = {')
    for b in BUILDS:
        w = FIT["worn"][b]
        o.append(f'\t{b} = {{ Disc = {lua_cf(w["Disc"])}, Text = {lua_cf(w["Text"])}, Ribbon = {lua_cf(w["Ribbon"])} }},')
    o.append('}')
    o.append('')
    for key, name in (("held", "Held"), ("heldOpen", "HeldOpen")):
        h = FIT[key]
        o.append(f'-- The referee\'s {"held" if key == "held" else "opened (over the head)"} medal, in its ribbon part\'s own space.')
        line = (f'CeremonyConfig.{name} = {{ holdPlusX = {lua_v3(h["holdPointPlusX"])}, holdMinusX = {lua_v3(h["holdPointMinusX"])}, '
                f'holdMidpoint = {lua_v3(h["holdMidpoint"])}, Disc = {lua_v3(h["Disc"])}, Text = {lua_v3(h["Text"])} }}')
        o.append(line)
    o.append('-- The opened ribbon in place of the held one: open.CFrame = held.CFrame * this.')
    o.append(f'CeremonyConfig.OpenFromHeld = CFrame.new({", ".join(f"{x:g}" for x in FIT["heldOpen"]["fromHeldRibbon"])})')
    o.append('-- Each hold point sits on the Grip hole of a hand: this far from its WristRigAttachment (left hand +X, right -X).')
    o.append('CeremonyConfig.GripFromWrist = Vector3.new(0.2455, -0.442, 0)')
    o.append('')
    o.append('CeremonyConfig.Animations = {')
    for k, v in ANIMATIONS.items():
        o.append(f'\t{k} = "{v}",')
    o.append('}')
    o.append('CeremonyConfig.TakeTrophy = {')
    for b in BUILDS:
        o.append(f'\t{b} = "{TAKE_TROPHY[b]}",')
    o.append('}')
    o.append('')
    o.append('CeremonyConfig.Times = {')
    o.append('\tMedalLength = 3.0, MedalOpenFrom = 0.90, MedalOpenTo = 1.50, MedalOnNeck = 1.85, MedalLetGo = 1.98,')
    o.append('\tHandshakeLength = 2.5, HandshakeFrom = 0.62, HandshakeTo = 1.78,')
    o.append('\tTrophyLength = 3.0, TrophyTaken = 1.25, TrophyRefLetGo = 1.32,')
    o.append('\tStepLength = 1.2, StepLaunch = 0.40, StepLand = 0.80,')
    o.append('}')
    o.append('')
    o.append('CeremonyConfig.Place = {')
    o.append('\tMedal = { ' + ", ".join(f'{b} = {{ x = 0, d = {MEDAL_D[b]} }}' for b in BUILDS) + ' },')
    o.append('\tHandshake = { ' + ", ".join(f'{b} = {{ x = {HANDSHAKE[b][0]}, d = {HANDSHAKE[b][1]} }}' for b in BUILDS) + ' },')
    o.append(f'\tTrophy = {{ x = 0, d = {TROPHY_D} }},')
    o.append('}')
    o.append('')
    o.append('-- The trophy once taken: its pivot from the lifter\'s RightWristRigAttachment.')
    o.append('CeremonyConfig.TrophyInLifterHand = {')
    for b in BUILDS:
        x, y, z = TROPHY_LIFTER_POS[b]
        o.append(f'\t{b} = CFrame.new({x}, {y}, {z}) * CFrame.fromEulerAnglesXYZ(-1.8158, 0, 0),')
    o.append('}')
    o.append('CeremonyConfig.TrophyInRefHand = CFrame.new(-0.553, -0.37, 0.066) * CFrame.fromEulerAnglesXYZ(-1.5621, 0, -3.1416)')
    o.append('')
    o.append('-- The hop onto the block: the lifter starts this far in front of its face (the arc then carries him onto its middle).')
    o.append('CeremonyConfig.StepFromFace = 0.9')
    o.append('')
    o.append('return CeremonyConfig')
    o.append('')
    OUT.write_text("\n".join(o), encoding="utf-8", newline="\n")
    print("wrote", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
