"""Write src/shared/Config/CoachVoiceConfig.luau from art/sounds/coach_voice_lines.json (after the upload).

    python art/scripts/make_coach_voice_config.py

Each coach's lines by key with their uploaded ids, and the words each meet line shows in the game (so a bubble's text
finds its take). The gym talk-screen lines (D1-D11) are said by key: their takes speak numbers as words.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "art" / "sounds" / "coach_voice_lines.json"
OUT = ROOT / "src" / "shared" / "Config" / "CoachVoiceConfig.luau"
ORDER = ["Squat", "Bench", "Deadlift", "Owner"]


def lua(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    sounds = json.loads(MANIFEST.read_text(encoding="utf-8"))["sounds"]
    by = {}
    for entry in sounds.values():
        by.setdefault(entry["lift"], []).append(entry)
    out = ['--!strict', '--[[', '\tCoachVoiceConfig', '\tShared / Config', '',
           '\tGENERATED by art/scripts/make_coach_voice_config.py from art/sounds/coach_voice_lines.json: do not edit by hand.',
           '\tEach coach\'s voice lines (ElevenLabs, his own fixed voice: art/sounds/coach_voices.json), by key, with the',
           '\tuploaded take and the words the line shows. Squat = Coach Squatavious, Bench = Coach Benchamin, Deadlift = Coach',
           '\tSumo, Owner = the Gym Owner. Keys: R ready, G good lift, M missed lift, S send-off slap, A attempt advice, E end',
           '\tof meet, T gear trial, C Mock Meet trial, D gym talk screen (said by key: CoachDialogue); round 3: W big',
           '\twalk-out (an attempt that decides places), H big yell after a big made lift, P end-of-meet scene, U coach',
           '\tunlock (lift coaches only). Played by CoachVoice.',
           ']]', '', 'export type Line = { id: string, text: string, seconds: number }', '',
           'local CoachVoiceConfig = {}', '',
           '-- Loudness of a coach line (the takes are all made one loudness; meets are loud).',
           'CoachVoiceConfig.Volume = 1.6', '',
           'CoachVoiceConfig.Lines = {']
    for lift in ORDER:
        out.append(f'\t{lift} = {{')
        for e in by.get(lift, []):
            out.append(f'\t\t{e["key"]} = {{ id = {lua(e["ids"].get("audio", ""))}, text = {lua(e["text"])}, seconds = {e["seconds"]} }},')
        out.append('\t},')
    out += ['} :: { [string]: { [string]: Line } }', '',
            '-- Each coach\'s meet-line words -> key (the talk-screen D lines are left out: said by key).',
            'CoachVoiceConfig.ByText = {} :: { [string]: { [string]: string } }',
            'for voice, lines in pairs(CoachVoiceConfig.Lines) do',
            '\tlocal byText = {}',
            '\tfor key, line in pairs(lines) do',
            '\t\tif string.sub(key, 1, 1) ~= "D" then',
            '\t\t\tbyText[line.text] = key',
            '\t\tend',
            '\tend',
            '\tCoachVoiceConfig.ByText[voice] = byText',
            'end', '', 'return CoachVoiceConfig', '']
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    missing = [n for n, e in sounds.items() if not e["ids"].get("audio")]
    print(f"wrote {OUT.relative_to(ROOT)}: {len(sounds)} lines, {len(missing)} without an id")


if __name__ == "__main__":
    main()
